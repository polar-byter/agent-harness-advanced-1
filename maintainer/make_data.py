def write_journal(path: Path) -> None:
    book = Workbook()
    sheet = book.active
    sheet.title = 'Журнал'
    sheet.append(['Дата', 'Кто записал', 'Что случилось'])
    for row in JOURNAL:
        sheet.append(row)
    for column, width in zip('ABC', (12, 14, 60)):
        sheet.column_dimensions[column].width = width
    path.parent.mkdir(parents=True, exist_ok=True)
    book.save(path)


